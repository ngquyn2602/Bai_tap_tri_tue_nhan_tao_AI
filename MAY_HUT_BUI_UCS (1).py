# 3. THUẬT TOÁN UCS
# =========================

def uniform_cost_search(start, dirt_positions):
    """
    State = (vị trí máy hút bụi, tập rác còn lại)
    Goal = không còn rác nào
    g(n) = tổng chi phí từ start đến trạng thái hiện tại
    """

    start_state = (start, frozenset(dirt_positions))

    # Frontier là priority queue
    # Mỗi phần tử: (cost, id, state, path, actions)
    frontier = []
    counter = 0

    heapq.heappush(frontier, (0, counter, start_state, [start], []))

    # Reached lưu chi phí nhỏ nhất đã biết tới mỗi state
    reached = {
        start_state: 0
    }

    log = []
    step = 0

    while frontier:
        cost, _, current_state, path, actions = heapq.heappop(frontier)

        current_pos, remaining_dirt = current_state

        # Nếu state này đã có đường tốt hơn trước đó thì bỏ qua
        if cost > reached[current_state]:
            continue

        step += 1

        log.append({
            "Step": step,
            "Node": state_to_string(current_state),
            "g": cost,
            "Frontier size": len(frontier),
            "Reached size": len(reached)
        })

        # Goal test
        if len(remaining_dirt) == 0:
            return {
                "cost": cost,
                "path": path,
                "actions": actions,
                "log": log,
                "reached": reached
            }

        # Nếu đang đứng trên ô có rác thì có thể hút
        if current_pos in remaining_dirt:
            new_remaining_dirt = set(remaining_dirt)
            new_remaining_dirt.remove(current_pos)

            new_state = (current_pos, frozenset(new_remaining_dirt))
            new_cost = cost + SUCK_COST

            if new_state not in reached or new_cost < reached[new_state]:
                reached[new_state] = new_cost
                counter += 1

                heapq.heappush(
                    frontier,
                    (
                        new_cost,
                        counter,
                        new_state,
                        path + [current_pos],
                        actions + [f"Suck dirt at {current_pos}"]
                    )
                )

        # Di chuyển sang các ô lân cận
        for action, new_pos, move_cost in get_neighbors(current_pos):
            new_state = (new_pos, remaining_dirt)
            new_cost = cost + move_cost

            if new_state not in reached or new_cost < reached[new_state]:
                reached[new_state] = new_cost
                counter += 1

                heapq.heappush(
                    frontier,
                    (
                        new_cost,
                        counter,
                        new_state,
                        path + [new_pos],
                        actions + [f"Move {action} to {new_pos}, cost={move_cost}"]
                    )
                )

    return None


