current_step = 0

output = widgets.Output()

btn_prev = widgets.Button(description="◀ Previous")
btn_next = widgets.Button(description="Next ▶")
btn_auto = widgets.Button(description="Auto Run")
btn_reset = widgets.Button(description="Reset")

step_label = widgets.Label()


def update_display():
    global current_step

    with output:
        clear_output(wait=True)

        step_label.value = f"Step {current_step}/{len(step_data) - 1}"

        draw_step(step_data[current_step])


def on_prev_clicked(b):
    global current_step

    if current_step > 0:
        current_step -= 1

    update_display()


def on_next_clicked(b):
    global current_step

    if current_step < len(step_data) - 1:
        current_step += 1

    update_display()


def on_reset_clicked(b):
    global current_step

    current_step = 0
    update_display()


def on_auto_clicked(b):
    global current_step

    while current_step < len(step_data) - 1:
        current_step += 1
        update_display()
        time.sleep(0.7)


btn_prev.on_click(on_prev_clicked)
btn_next.on_click(on_next_clicked)
btn_reset.on_click(on_reset_clicked)
btn_auto.on_click(on_auto_clicked)

controls = widgets.HBox([btn_prev, btn_next, btn_auto, btn_reset])
display(widgets.VBox([step_label, controls, output]))

update_display()