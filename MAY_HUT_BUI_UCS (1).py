# Tạo dữ liệu từng bước từ result["path"] và result["actions"]
def build_step_data(result, dirt_positions):
    path = result["path"]
    actions = result["actions"]

    step_data = []
    remaining_dirt = set(dirt_positions)
    total_cost = 0

    # Step 0: trạng thái ban đầu
    step_data.append({
        "step": 0,
        "pos": path[0],
        "action": "Start",
        "cost": total_cost,
        "remaining_dirt": set(remaining_dirt)
    })

    for i in range(1, len(path)):
        prev_pos = path[i - 1]
        current_pos = path[i]

        # Nếu vị trí không đổi nghĩa là đang hút bụi
        if current_pos == prev_pos:
            total_cost += SUCK_COST
            if current_pos in remaining_dirt:
                remaining_dirt.remove(current_pos)
            action_text = f"Suck dirt at {current_pos}, cost={SUCK_COST}"
        else:
            move_cost = grid[current_pos[0]][current_pos[1]]
            total_cost += move_cost

            # Lấy action trong result nếu có
            if i - 1 < len(actions):
                action_text = actions[i - 1]
            else:
                action_text = f"Move to {current_pos}, cost={move_cost}"

        step_data.append({
            "step": i,
            "pos": current_pos,
            "action": action_text,
            "cost": total_cost,
            "remaining_dirt": set(remaining_dirt)
        })

    return step_data


step_data = build_step_data(result, dirt_positions)


