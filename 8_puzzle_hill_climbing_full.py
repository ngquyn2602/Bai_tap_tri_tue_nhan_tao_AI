def build_problem(
    start_text: str,
    goal_text: str,
    move_order: str = "LRUD",
    heuristic_name: str = "misplaced",
) -> PuzzleProblem:
    order = "".join(ch for ch in move_order.upper() if ch in "LRUD")
    if not order:
        order = "LRUD"

    return PuzzleProblem(
        start=parse_board(start_text),
        goal=parse_board(goal_text),
        move_order=order,
        heuristic_name=heuristic_name,
    )



def run_algorithm(
    algorithm_name: str,
    start_text: str,
    goal_text: str,
    move_order: str = "LRUD",
    heuristic_name: str = "misplaced",
    max_steps: int = 100,
    seed: int = 42,
    restarts: int = 10,
    random_walk_steps: int = 25,
    show_trace: bool = True,
) -> SearchReport:
    if NOTEBOOK_MODE:
        clear_output(wait=True)

    problem = build_problem(start_text, goal_text, move_order, heuristic_name)
    load_theme()

    heuristic_label = "số ô sai vị trí" if heuristic_name == "misplaced" else "Manhattan"
    show_html(f"""
    <div class='box-note'>
        <b>Ý nghĩa:</b> Ta xem mỗi trạng thái 8-puzzle là một node.<br>
        <b>Frontier:</b> các trạng thái sinh ra khi di chuyển ô trống theo thứ tự
        <span class='small-code'>{html.escape(problem.move_order)}</span>.<br>
        <b>Reached:</b> các node đã đi qua trong lần chạy hiện tại.<br>
        <b>Heuristic đang dùng:</b> h(n) = {heuristic_label}.<br>
        <b>Mục tiêu:</b> làm h(n) giảm dần về 0.
    </div>
    """)

    if not same_parity(problem.start, problem.goal):
        show_html("""
        <div class='box-warn'>
            <b>Cảnh báo:</b> Start và Goal khác parity nghịch thế. Với 8-puzzle 3x3,
            trường hợp này thường không giải được bằng chuỗi di chuyển hợp lệ.
        </div>
        """)

    if algorithm_name == "Leo đồi khởi động lại ngẫu nhiên":
        report = random_restart_hill_climbing(
            problem=problem,
            max_steps=max_steps,
            seed=seed,
            restarts=restarts,
            random_walk_steps=random_walk_steps,
        )
    else:
        fn = ALGORITHM_MAP[algorithm_name]
        report = fn(problem, max_steps=max_steps, seed=seed)

    show_report(problem, report, show_trace=show_trace)
    return report



def compare_all_algorithms(
    start_text: str,
    goal_text: str,
    move_order: str = "LRUD",
    heuristic_name: str = "misplaced",
    max_steps: int = 100,
    seed: int = 42,
    restarts: int = 10,
    random_walk_steps: int = 25,
) -> List[SearchReport]:
    if NOTEBOOK_MODE:
        clear_output(wait=True)

    problem = build_problem(start_text, goal_text, move_order, heuristic_name)
    load_theme()
    reports: List[SearchReport] = []

    reports.append(simple_hill_climbing(problem, max_steps=max_steps, seed=seed))
    reports.append(steepest_hill_climbing(problem, max_steps=max_steps, seed=seed))
    reports.append(stochastic_hill_climbing(problem, max_steps=max_steps, seed=seed))
    reports.append(random_restart_hill_climbing(
        problem,
        max_steps=max_steps,
        seed=seed,
        restarts=restarts,
        random_walk_steps=random_walk_steps,
    ))

    show_html("<div class='eight-title'>So sánh đủ 4 thuật toán</div>")
    show_html(board_card(problem, problem.start, "Start") + board_card(problem, problem.goal, "Goal"))

    rows = ""
    for report in reports:
        final_h = problem.h(report.path[-1])
        rows += f"""
        <tr>
            <td>{html.escape(report.algorithm)}</td>
            <td>{html.escape(report.status)}</td>
            <td>{max(0, len(report.path) - 1)}</td>
            <td>{final_h}</td>
            <td>{html.escape(report.message)}</td>
        </tr>
        """

    show_html(f"""
    <table class='step-table'>
        <tr>
            <th>Thuật toán</th>
            <th>Trạng thái</th>
            <th>Số bước path</th>
            <th>h cuối</th>
            <th>Nhận xét</th>
        </tr>
        {rows}
    </table>
    """)

    return reports


