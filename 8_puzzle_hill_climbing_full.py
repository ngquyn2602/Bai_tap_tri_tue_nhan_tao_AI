def board_card(problem: PuzzleProblem, board: Board, title: str) -> str:
    cells = ""
    for r in range(3):
        cells += "<tr>"
        for c in range(3):
            value = board[r * 3 + c]
            cls = "blank" if value == 0 else ""
            shown = "&nbsp;" if value == 0 else str(value)
            cells += f"<td class='{cls}'>{shown}</td>"
        cells += "</tr>"

    return f"""
    <div class='board-card'>
        <div class='board-name'>{html.escape(title)}</div>
        <div class='board-score'>h = {problem.h(board)}</div>
        <table class='grid3'>{cells}</table>
    </div>
    """



def frontier_text(problem: PuzzleProblem, items: Sequence[Tuple[Move, Board, int]], names: NameBook) -> str:
    if not items:
        return "[]"
    parts = []
    for mv, board, hval in items:
        parts.append(f"({mv}→{names.name(board)}, h={hval})")
    return "[" + ", ".join(parts) + "]"



def chosen_text(chosen: Optional[Tuple[Move, Board, int]], names: NameBook) -> str:
    if chosen is None:
        return "Không chọn"
    mv, board, hval = chosen
    return f"{mv} → {names.name(board)}, h={hval}"



def add_step(
    trace: List[StepRecord],
    problem: PuzzleProblem,
    names: NameBook,
    restart: int,
    step: int,
    board: Board,
    frontier: Sequence[Tuple[Move, Board, int]],
    chosen: Optional[Tuple[Move, Board, int]],
    reached: Sequence[Board],
    note: str,
) -> None:
    trace.append(
        StepRecord(
            restart=restart,
            step=step,
            node=names.name(board),
            board=board,
            h_node=problem.h(board),
            frontier=frontier_text(problem, frontier, names),
            chosen=chosen_text(chosen, names),
            reached=names.reached_text(reached),
            note=note,
        )
    )



def trace_to_html(trace: Sequence[StepRecord]) -> str:
    if not trace:
        return "<div class='box-note'>Không có bước nào để hiển thị.</div>"

    headers = [
        "Restart", "Step", "Node", "Ma trận hiện tại", "h(Node)",
        "Frontier / Neighbor", "Node chọn", "Reached", "Ghi chú"
    ]

    rows = ""
    for item in trace:
        matrix = html.escape(board_to_lines(item.board))
        rows += f"""
        <tr>
            <td>{item.restart}</td>
            <td>{item.step}</td>
            <td><b>{item.node}</b></td>
            <td><div class='matrix-text'>{matrix}</div></td>
            <td>{item.h_node}</td>
            <td>{html.escape(item.frontier)}</td>
            <td>{html.escape(item.chosen)}</td>
            <td>{html.escape(item.reached)}</td>
            <td>{html.escape(item.note)}</td>
        </tr>
        """

    head = "".join(f"<th>{h}</th>" for h in headers)
    return f"<table class='step-table'><tr>{head}</tr>{rows}</table>"



def path_to_html(problem: PuzzleProblem, path: Sequence[Board], moves: Sequence[Move]) -> str:
    if not path:
        return ""

    content = "<div class='path-line'>"
    for i, board in enumerate(path):
        content += board_card(problem, board, f"Bước {i}")
        if i < len(path) - 1:
            mv = moves[i] if i < len(moves) else "?"
            content += f"<div class='arrow'>→<span class='move-label'>{mv}</span></div>"
    content += "</div>"
    return content



def show_report(problem: PuzzleProblem, report: SearchReport, show_trace: bool = True) -> None:
    load_theme()

    if report.status == "success":
        box = "box-good"
    elif report.status == "stuck":
        box = "box-warn"
    else:
        box = "box-bad"

    final_h = problem.h(report.path[-1]) if report.path else "?"
    show_html(f"""
    <div class='eight-wrap'>
        <div class='eight-title'>{html.escape(report.algorithm)}</div>
        <div class='{box}'>
            <b>Kết quả:</b> {html.escape(report.message)}<br>
            <b>Trạng thái:</b> {html.escape(report.status)}<br>
            <b>Số bước path:</b> {max(0, len(report.path) - 1)}<br>
            <b>h cuối:</b> {final_h}
        </div>
    </div>
    """)

    show_html("<div class='eight-title'>Start và Goal</div>")
    show_html(board_card(problem, problem.start, "Start") + board_card(problem, problem.goal, "Goal"))

    if show_trace:
        show_html("<div class='eight-title'>Bảng Node – Frontier – Reached</div>")
        show_html(trace_to_html(report.trace))

    show_html("<div class='eight-title'>Đường đi</div>")
    show_html(path_to_html(problem, report.path, report.moves))


