def choose_first_better(
    problem: PuzzleProblem,
    current: Board,
    frontier: List[Tuple[Move, Board, int]],
    reached: List[Board],
    rng: random.Random,
) -> Optional[Tuple[Move, Board, int]]:
    """Leo đồi đơn giản: gặp neighbor nào tốt hơn đầu tiên thì chọn ngay."""
    current_h = problem.h(current)
    for item in frontier:
        if item[2] < current_h:
            return item
    return None



def choose_best_better(
    problem: PuzzleProblem,
    current: Board,
    frontier: List[Tuple[Move, Board, int]],
    reached: List[Board],
    rng: random.Random,
) -> Optional[Tuple[Move, Board, int]]:
    """Leo đồi dốc nhất: xét hết frontier rồi chọn neighbor có h nhỏ nhất."""
    current_h = problem.h(current)
    if not frontier:
        return None

    best = min(frontier, key=lambda item: item[2])
    if best[2] < current_h:
        return best
    return None



def choose_random_better(
    problem: PuzzleProblem,
    current: Board,
    frontier: List[Tuple[Move, Board, int]],
    reached: List[Board],
    rng: random.Random,
) -> Optional[Tuple[Move, Board, int]]:
    """Leo đồi ngẫu nhiên: lọc các neighbor tốt hơn rồi bốc ngẫu nhiên 1 node."""
    current_h = problem.h(current)
    better = [item for item in frontier if item[2] < current_h]
    if not better:
        return None
    return rng.choice(better)



def simple_hill_climbing(problem: PuzzleProblem, max_steps: int = 100, seed: int = 42) -> SearchReport:
    return local_search_core(
        problem=problem,
        algorithm_name="1. Leo đồi đơn giản / First-choice Hill Climbing",
        chooser=choose_first_better,
        max_steps=max_steps,
        seed=seed,
    )



def steepest_hill_climbing(problem: PuzzleProblem, max_steps: int = 100, seed: int = 42) -> SearchReport:
    return local_search_core(
        problem=problem,
        algorithm_name="2. Leo đồi dốc nhất / Steepest-ascent Hill Climbing",
        chooser=choose_best_better,
        max_steps=max_steps,
        seed=seed,
    )



def stochastic_hill_climbing(problem: PuzzleProblem, max_steps: int = 100, seed: int = 42) -> SearchReport:
    return local_search_core(
        problem=problem,
        algorithm_name="3. Leo đồi ngẫu nhiên / Stochastic Hill Climbing",
        chooser=choose_random_better,
        max_steps=max_steps,
        seed=seed,
    )



def random_restart_hill_climbing(
    problem: PuzzleProblem,
    max_steps: int = 100,
    seed: int = 42,
    restarts: int = 10,
    random_walk_steps: int = 25,
) -> SearchReport:
    """
    Chạy nhiều lần leo đồi dốc nhất.
    Restart 0 dùng Start ban đầu.
    Các restart sau tạo state ngẫu nhiên bằng cách đi random từ Goal.
    """
    master_rng = random.Random(seed)
    all_trace: List[StepRecord] = []
    best_path: List[Board] = [problem.start]
    best_moves: List[Move] = []
    best_h = problem.h(problem.start)

    for rid in range(restarts + 1):
        if rid == 0:
            candidate_start = problem.start
        else:
            candidate_start = make_random_solvable_board(
                goal=problem.goal,
                steps=random_walk_steps,
                rng=master_rng,
            )

        attempt = local_search_core(
            problem=problem,
            algorithm_name="4. Leo đồi khởi động lại ngẫu nhiên / Random-restart Hill Climbing",
            chooser=choose_best_better,
            max_steps=max_steps,
            seed=master_rng.randint(1, 10**9),
            restart_id=rid,
            forced_start=candidate_start,
        )

        all_trace.extend(attempt.trace)
        last_h = problem.h(attempt.path[-1])

        if last_h < best_h:
            best_h = last_h
            best_path = attempt.path
            best_moves = attempt.moves

        if attempt.status == "success":
            return SearchReport(
                algorithm="4. Leo đồi khởi động lại ngẫu nhiên / Random-restart Hill Climbing",
                status="success",
                message=f"Tìm thấy goal ở restart {rid}.",
                path=attempt.path,
                moves=attempt.moves,
                trace=all_trace,
            )

    return SearchReport(
        algorithm="4. Leo đồi khởi động lại ngẫu nhiên / Random-restart Hill Climbing",
        status="stuck",
        message=f"Chưa tìm thấy goal sau {restarts} lần restart. Path tốt nhất có h = {best_h}.",
        path=best_path,
        moves=best_moves,
        trace=all_trace,
    )


