@dataclass(frozen=True)
class PuzzleProblem:
    start: Board
    goal: Board
    move_order: str = "LRUD"
    heuristic_name: str = "misplaced"

    def h(self, board: Board) -> int:
        if self.heuristic_name == "manhattan":
            return manhattan_distance(board, self.goal)
        return misplaced_count(board, self.goal)

    def expand(self, board: Board) -> List[Tuple[Move, Board, int]]:
        """Trả về danh sách neighbor theo đúng thứ tự L R U D."""
        result: List[Tuple[Move, Board, int]] = []
        for mv in self.move_order:
            new_board = slide_blank(board, mv)
            if new_board is not None:
                result.append((mv, new_board, self.h(new_board)))
        return result

    def goal_test(self, board: Board) -> bool:
        return board == self.goal


