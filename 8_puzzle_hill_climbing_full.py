Chooser = Callable[[PuzzleProblem, Board, List[Tuple[Move, Board, int]], List[Board], random.Random], Optional[Tuple[Move, Board, int]]]



def local_search_core(
    problem: PuzzleProblem,
    algorithm_name: str,
    chooser: Chooser,
    max_steps: int,
    seed: int,
    restart_id: int = 0,
    forced_start: Optional[Board] = None,
) -> SearchReport:
    rng = random.Random(seed)
    names = NameBook()
    current = forced_start if forced_start is not None else problem.start
    path: List[Board] = [current]
    moves: List[Move] = []
    reached: List[Board] = [current]
    reached_set = {current}
    trace: List[StepRecord] = []

    for step in range(max_steps + 1):
        if problem.goal_test(current):
            add_step(
                trace, problem, names, restart_id, step, current, [], None, reached,
                "Đã tới goal nên dừng."
            )
            return SearchReport(
                algorithm=algorithm_name,
                status="success",
                message="Tìm thấy goal.",
                path=path,
                moves=moves,
                trace=trace,
            )

        frontier = problem.expand(current)
        frontier = [item for item in frontier if item[1] not in reached_set]
        chosen = chooser(problem, current, frontier, reached, rng)

        if chosen is None:
            add_step(
                trace, problem, names, restart_id, step, current, frontier, None, reached,
                "Không chọn được node tốt hơn → bị kẹt tại local optimum/plateau."
            )
            return SearchReport(
                algorithm=algorithm_name,
                status="stuck",
                message="Không tìm thấy goal vì bị kẹt tại cực trị cục bộ hoặc vùng bằng phẳng.",
                path=path,
                moves=moves,
                trace=trace,
            )

        mv, new_board, new_h = chosen
        add_step(
            trace, problem, names, restart_id, step, current, frontier, chosen, reached,
            f"Đi theo move {mv} vì h giảm từ {problem.h(current)} xuống {new_h}."
        )

        current = new_board
        path.append(current)
        moves.append(mv)
        reached.append(current)
        reached_set.add(current)

    return SearchReport(
        algorithm=algorithm_name,
        status="cutoff",
        message=f"Dừng vì vượt quá max_steps = {max_steps}.",
        path=path,
        moves=moves,
        trace=trace,
    )


