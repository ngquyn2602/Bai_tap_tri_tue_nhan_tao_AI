def parse_board(text: str) -> Board:
    """Nhập được cả dạng nhiều dòng hoặc có dấu /."""
    cleaned = text.replace("/", " ").replace(",", " ")
    values = [int(x) for x in cleaned.split()]

    if len(values) != 9:
        raise ValueError("Bạn phải nhập đúng 9 số.")
    if sorted(values) != list(range(9)):
        raise ValueError("Bảng phải có đủ các số 0,1,2,3,4,5,6,7,8 và không trùng.")

    return tuple(values)



def board_to_lines(board: Board) -> str:
    return "\n".join(
        " ".join(str(x) for x in board[i:i + 3])
        for i in range(0, 9, 3)
    )



def misplaced_count(board: Board, goal: Board) -> int:
    """h(n) = số ô sai vị trí, không tính ô 0."""
    wrong = 0
    for i, value in enumerate(board):
        if value != 0 and value != goal[i]:
            wrong += 1
    return wrong



def manhattan_distance(board: Board, goal: Board) -> int:
    """Tổng khoảng cách Manhattan, không tính ô 0."""
    goal_pos = {value: index for index, value in enumerate(goal)}
    total = 0
    for index, value in enumerate(board):
        if value == 0:
            continue
        r1, c1 = divmod(index, 3)
        r2, c2 = divmod(goal_pos[value], 3)
        total += abs(r1 - r2) + abs(c1 - c2)
    return total



def count_inversions(board: Board) -> int:
    arr = [x for x in board if x != 0]
    inv = 0
    for i in range(len(arr)):
        for j in range(i + 1, len(arr)):
            if arr[i] > arr[j]:
                inv += 1
    return inv



def same_parity(start: Board, goal: Board) -> bool:
    return count_inversions(start) % 2 == count_inversions(goal) % 2



def slide_blank(board: Board, move: Move) -> Optional[Board]:
    zero = board.index(0)
    r, c = divmod(zero, 3)
    target: Optional[int] = None

    if move == "L" and c > 0:
        target = zero - 1
    elif move == "R" and c < 2:
        target = zero + 1
    elif move == "U" and r > 0:
        target = zero - 3
    elif move == "D" and r < 2:
        target = zero + 3

    if target is None:
        return None

    new_board = list(board)
    new_board[zero], new_board[target] = new_board[target], new_board[zero]
    return tuple(new_board)



def make_random_solvable_board(goal: Board, steps: int, rng: random.Random) -> Board:
    """Tạo state ngẫu nhiên bằng cách đi ngẫu nhiên từ goal nên luôn giải được."""
    board = goal
    last_move: Optional[Move] = None
    opposite = {"L": "R", "R": "L", "U": "D", "D": "U"}

    for _ in range(steps):
        options: List[Tuple[Move, Board]] = []
        for mv in "LRUD":
            if last_move is not None and mv == opposite[last_move]:
                continue
            nxt = slide_blank(board, mv)
            if nxt is not None:
                options.append((mv, nxt))

        if not options:
            for mv in "LRUD":
                nxt = slide_blank(board, mv)
                if nxt is not None:
                    options.append((mv, nxt))

        last_move, board = rng.choice(options)

    return board


