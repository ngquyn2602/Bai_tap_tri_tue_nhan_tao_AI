class NameBook:
    """Đặt tên N0, N1, N2... cho các trạng thái để bảng dễ đọc."""

    def __init__(self) -> None:
        self._names: Dict[Board, str] = {}

    def name(self, board: Board) -> str:
        if board not in self._names:
            self._names[board] = f"N{len(self._names)}"
        return self._names[board]

    def reached_text(self, boards: Iterable[Board], limit: int = 10) -> str:
        names = [self.name(b) for b in boards]
        if len(names) <= limit:
            return "{" + ", ".join(names) + "}"
        head = ", ".join(names[:limit])
        return "{" + head + f", ... +{len(names) - limit}" + "}"


