class PuzzleProblem:
    def __init__(self, goal):
        self.goal = goal
        self.goal_location = self._make_goal_location(goal)

    def parse(self, text):
        text = text.replace(",", " ")
        text = text.replace("/", " ")
        text = text.replace("X", "0")
        text = text.replace("x", "0")

        raw = text.split()

        if len(raw) != 9:
            raise ValueError("Bạn phải nhập đúng 9 ô. Ví dụ: 1 2 3 / 4 8 X / 7 6 5")

        try:
            state = tuple(int(x) for x in raw)
        except:
            raise ValueError("Chỉ được nhập các số 0-8 hoặc X.")

        if set(state) != set(range(9)):
            raise ValueError("Trạng thái phải có đủ 0,1,2,3,4,5,6,7,8 và không được trùng.")

        return state

    def state_to_text(self, state):
        lines = []

        for i in range(0, 9, 3):
            row = []

            for value in state[i:i + 3]:
                row.append("X" if value == 0 else str(value))

            lines.append(" ".join(row))

        return "\n".join(lines)

    def state_to_line(self, state):
        return self.state_to_text(state).replace("\n", " / ")

    def _make_goal_location(self, goal):
        pos = {}

        for index, value in enumerate(goal):
            pos[value] = (index // 3, index % 3)

        return pos

    def inversion_count(self, state):
        arr = [x for x in state if x != 0]
        count = 0

        for i in range(len(arr)):
            for j in range(i + 1, len(arr)):
                if arr[i] > arr[j]:
                    count += 1

        return count

    def can_solve(self, start):
        return self.inversion_count(start) % 2 == self.inversion_count(self.goal) % 2

    def manhattan(self, state):
        total = 0

        for index, value in enumerate(state):
            if value == 0:
                continue

            r = index // 3
            c = index % 3

            gr, gc = self.goal_location[value]

            total += abs(r - gr) + abs(c - gc)

        return total

    def misplaced(self, state):
        wrong = 0

        for current, target in zip(state, self.goal):
            if current != 0 and current != target:
                wrong += 1

        return wrong

    def heuristic(self, state, kind):
        if kind == "MANHATTAN":
            return self.manhattan(state)

        if kind == "MISPLACED":
            return self.misplaced(state)

        return 0

    def expand(self, state):
        blank = state.index(0)
        r = blank // 3
        c = blank % 3

        directions = [
            ("Lên", -1, 0),
            ("Xuống", 1, 0),
            ("Trái", 0, -1),
            ("Phải", 0, 1),
        ]

        children = []

        for move_name, dr, dc in directions:
            nr = r + dr
            nc = c + dc

            if 0 <= nr < 3 and 0 <= nc < 3:
                new_blank = nr * 3 + nc

                temp = list(state)
                tile = temp[new_blank]

                temp[blank], temp[new_blank] = temp[new_blank], temp[blank]

                children.append({
                    "state": tuple(temp),
                    "move": move_name,
                    "tile": tile
                })

        return children


