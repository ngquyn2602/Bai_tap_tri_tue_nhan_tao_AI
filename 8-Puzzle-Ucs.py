class SearchMachine:
    def __init__(self, problem, start, algorithm, heuristic_kind, max_nodes):
        self.problem = problem
        self.start = start
        self.goal = problem.goal
        self.algorithm = algorithm
        self.heuristic_kind = heuristic_kind
        self.max_nodes = max_nodes

        self.counter = itertools.count()

        self.frontier = []
        self.best_cost = {}
        self.parent = {}
        self.move_record = {}
        self.expanded_set = set()
        self.expanded_order = []
        self.steps = []

    def priority_of(self, g, h):
        if self.algorithm == "UCS":
            return g

        if self.algorithm == "GREEDY":
            return h

        return g

    def active_frontier(self):
        active = []

        for priority, order, state, g in self.frontier:
            if state in self.expanded_set:
                continue

            if self.best_cost.get(state) != g:
                continue

            h = self.problem.heuristic(state, self.heuristic_kind)

            active.append({
                "state": state,
                "g": g,
                "h": h,
                "priority": priority,
                "order": order
            })

        active.sort(key=lambda x: (x["priority"], x["order"]))

        return active

    def reached_snapshot(self):
        data = []

        for state, g in self.best_cost.items():
            data.append({
                "state": state,
                "g": g,
                "h": self.problem.heuristic(state, self.heuristic_kind),
                "parent": self.parent.get(state)
            })

        data.sort(key=lambda x: (x["g"], x["h"], self.problem.state_to_line(x["state"])))

        return data

    def make_path(self, target):
        if target not in self.parent:
            return []

        path = []
        cur = target

        while cur is not None:
            path.append(cur)
            cur = self.parent.get(cur)

        path.reverse()

        return path

    def make_moves(self, target):
        moves = []
        cur = target

        while cur != self.start:
            record = self.move_record.get(cur)

            if record is None:
                break

            moves.append(record)
            cur = record["from"]

        moves.reverse()

        return moves

    def push_start(self):
        g = 0
        h = self.problem.heuristic(self.start, self.heuristic_kind)
        p = self.priority_of(g, h)

        self.best_cost[self.start] = 0
        self.parent[self.start] = None

        heapq.heappush(
            self.frontier,
            (p, next(self.counter), self.start, g)
        )

    def pop_next(self):
        while self.frontier:
            priority, order, state, g = heapq.heappop(self.frontier)

            if state in self.expanded_set:
                continue

            if self.best_cost.get(state) != g:
                continue

            return priority, state, g

        return None, None, None

    def run(self):
        if not self.problem.can_solve(self.start):
            return {
                "status": "UNSOLVABLE",
                "message": "Start và Goal không cùng tính chẵn/lẻ nghịch thế nên không giải được.",
                "steps": []
            }

        self.push_start()

        step_number = 1

        while self.frontier and len(self.expanded_set) < self.max_nodes:
            frontier_before = self.active_frontier()

            current_priority, current_state, current_g = self.pop_next()

            if current_state is None:
                break

            current_h = self.problem.heuristic(current_state, self.heuristic_kind)

            self.expanded_set.add(current_state)
            self.expanded_order.append(current_state)

            current_path = self.make_path(current_state)
            current_moves = self.make_moves(current_state)

            messages = []
            child_logs = []

            if current_state == self.goal:
                if self.algorithm == "UCS":
                    messages.append(
                        "Đã lấy Goal ra khỏi Frontier. Với UCS, đây là đường đi tối ưu vì UCS luôn chọn g(n) nhỏ nhất."
                    )
                else:
                    messages.append(
                        "Đã lấy Goal ra khỏi Frontier. Với Greedy, thuật toán dừng nhưng đường đi chưa chắc tối ưu."
                    )

                frame = StepInfo(
                    number=step_number,
                    status="GOAL",
                    current=current_state,
                    g=current_g,
                    h=current_h,
                    priority=current_priority,
                    frontier_before=frontier_before,
                    frontier_after=self.active_frontier(),
                    children=[],
                    reached=self.reached_snapshot(),
                    expanded=list(self.expanded_order),
                    path=current_path,
                    moves=current_moves,
                    messages=messages
                )

                self.steps.append(frame)

                return {
                    "status": "GOAL",
                    "message": "Tìm thấy Goal.",
                    "cost": current_g,
                    "path": current_path,
                    "moves": current_moves,
                    "steps": self.steps
                }

            for item in self.problem.expand(current_state):
                child = item["state"]
                move = item["move"]
                tile = item["tile"]

                new_g = current_g + 1
                new_h = self.problem.heuristic(child, self.heuristic_kind)
                new_priority = self.priority_of(new_g, new_h)

                if child in self.expanded_set:
                    result = "SKIP"
                    note = "Node con đã nằm trong Expanded nên bỏ qua."

                elif child not in self.best_cost:
                    self.best_cost[child] = new_g
                    self.parent[child] = current_state
                    self.move_record[child] = {
                        "from": current_state,
                        "to": child,
                        "move": move,
                        "tile": tile,
                        "g": new_g,
                        "h": new_h,
                        "priority": new_priority
                    }

                    heapq.heappush(
                        self.frontier,
                        (new_priority, next(self.counter), child, new_g)
                    )

                    result = "ADD"

                    if self.algorithm == "UCS":
                        note = f"Node mới, thêm vào Frontier với priority = g(n) = {new_g}."
                    else:
                        note = f"Node mới, thêm vào Frontier với priority = h(n) = {new_h}."

                elif new_g < self.best_cost[child]:
                    old_g = self.best_cost[child]

                    self.best_cost[child] = new_g
                    self.parent[child] = current_state
                    self.move_record[child] = {
                        "from": current_state,
                        "to": child,
                        "move": move,
                        "tile": tile,
                        "g": new_g,
                        "h": new_h,
                        "priority": new_priority
                    }

                    heapq.heappush(
                        self.frontier,
                        (new_priority, next(self.counter), child, new_g)
                    )

                    result = "UPDATE"
                    note = f"Tìm được đường tốt hơn: g mới = {new_g} nhỏ hơn g cũ = {old_g}."

                else:
                    result = "SKIP"
                    note = f"Không tốt hơn đường cũ trong Reached. g mới = {new_g}, g cũ = {self.best_cost[child]}."

                child_logs.append(
                    ChildInfo(
                        state=child,
                        move=move,
                        swapped_tile=tile,
                        g=new_g,
                        h=new_h,
                        priority=new_priority,
                        result=result,
                        note=note
                    )
                )

                messages.append(
                    f"Di chuyển X {move}, đổi chỗ với ô {tile}: {note}"
                )

            frame = StepInfo(
                number=step_number,
                status="RUNNING",
                current=current_state,
                g=current_g,
                h=current_h,
                priority=current_priority,
                frontier_before=frontier_before,
                frontier_after=self.active_frontier(),
                children=child_logs,
                reached=self.reached_snapshot(),
                expanded=list(self.expanded_order),
                path=current_path,
                moves=current_moves,
                messages=messages
            )

            self.steps.append(frame)
            step_number += 1

        return {
            "status": "LIMIT",
            "message": f"Dừng vì vượt quá giới hạn mở rộng {self.max_nodes} node hoặc Frontier rỗng.",
            "steps": self.steps
        }


