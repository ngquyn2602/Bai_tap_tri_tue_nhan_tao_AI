def moves_table(moves):
    if not moves:
        return '<div class="new-note">Node hiện tại là Start nên chưa có bước di chuyển X.</div>'

    rows = ""

    for i, m in enumerate(moves, start=1):
        rows += f"""
        <tr>
            <td><b>{i}</b></td>
            <td>X đi {m["move"]}</td>
            <td>{m["tile"]}</td>
            <td>{m["g"]}</td>
            <td>{m["h"]}</td>
            <td>{m["priority"]}</td>
        </tr>
        """

    return f"""
    <table class="new-table">
        <tr>
            <th>Bước</th>
            <th>Hành động</th>
            <th>Đổi chỗ với ô</th>
            <th>g(n)</th>
            <th>h(n)</th>
            <th>priority</th>
        </tr>
        {rows}
    </table>
    """


def messages_view(messages):
    if not messages:
        return '<div class="new-note">Không có hành động.</div>'

    rows = ""

    for msg in messages:
        rows += f"<li>{html.escape(msg)}</li>"

    return f"""
    <ul style="font-size:18px; line-height:1.8;">
        {rows}
    </ul>
    """


def history_table(problem, steps, current_index, limit=15):
    rows = ""

    visible = steps[:current_index + 1]
    visible = visible[-limit:]

    for step in visible:
        rows += f"""
        <tr>
            <td><b>{step.number}</b></td>
            <td>{html.escape(problem.state_to_line(step.current))}</td>
            <td>{step.g}</td>
            <td>{step.h}</td>
            <td>{step.priority}</td>
            <td>{len(step.frontier_after)}</td>
            <td>{len(step.reached)}</td>
            <td>{len(step.expanded)}</td>
            <td>{step.status}</td>
        </tr>
        """

    return f"""
    <table class="new-table">
        <tr>
            <th>Bước</th>
            <th>Node đang xét</th>
            <th>g(n)</th>
            <th>h(n)</th>
            <th>priority</th>
            <th>Frontier sau</th>
            <th>Reached</th>
            <th>Expanded</th>
            <th>Trạng thái</th>
        </tr>
        {rows}
    </table>
    """


