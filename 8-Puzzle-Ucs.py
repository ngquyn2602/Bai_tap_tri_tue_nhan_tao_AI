def random_start_from_goal(problem, goal, steps):
    state = goal
    previous = None

    for _ in range(steps):
        children = problem.expand(state)

        choices = [
            child for child in children
            if child["state"] != previous
        ]

        if not choices:
            choices = children

        picked = random.choice(choices)

        previous = state
        state = picked["state"]

    return state


